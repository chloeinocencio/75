import Foundation
import UIKit

/// Persists progress photos as JPEG files under Application Support.
///
/// - Photos are never written to the photo library and never uploaded anywhere by 75.
/// - Every file is written with `.completeFileProtection`: it is encrypted with a key that
///   only exists while the iPhone is unlocked, so a locked or stolen phone can't read them.
/// - Application Support *is* included in the user's own encrypted iCloud/Finder device
///   backup, which is what lets photos survive moving to a new iPhone.
enum PhotoStorageService {
    private static let directory: URL = {
        let base = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        let dir = base.appendingPathComponent("ProgressPhotos", isDirectory: true)
        try? FileManager.default.createDirectory(
            at: dir,
            withIntermediateDirectories: true,
            attributes: [.protectionKey: FileProtectionType.complete]
        )
        return dir
    }()

    /// Resolves a stored file name to its URL. File names are generated by `save` and are
    /// only ever a single path component; anything else is refused so a corrupted record can
    /// never point outside the photo directory.
    static func url(for fileName: String) -> URL? {
        guard !fileName.isEmpty,
              !fileName.contains("/"),
              !fileName.contains(".."),
              fileName == (fileName as NSString).lastPathComponent
        else { return nil }
        return directory.appendingPathComponent(fileName)
    }

    static func save(_ image: UIImage, dayNumber: Int, pose: PhotoPose) throws -> String {
        // Phone captures are ~12 MP; 2400 px on the long edge is plenty for a full-screen
        // compare and keeps 75+ photos from eating gigabytes.
        let scaled = image.downscaled(maxPixelSize: 2400)
        guard let data = scaled.jpegData(compressionQuality: 0.85) else {
            throw PhotoStorageError.encodingFailed
        }
        let fileName = "day\(dayNumber)-\(pose.rawValue.lowercased())-\(UUID().uuidString).jpg"
        guard let url = url(for: fileName) else { throw PhotoStorageError.encodingFailed }
        try data.write(to: url, options: [.atomic, .completeFileProtection])
        return fileName
    }

    static func delete(fileName: String) {
        guard let url = url(for: fileName) else { return }
        try? FileManager.default.removeItem(at: url)
        ImageCache.shared.evict(fileName: fileName)
    }

    /// Removes every stored photo. Used by "Erase all data".
    static func deleteAll() {
        let files = (try? FileManager.default.contentsOfDirectory(at: directory, includingPropertiesForKeys: nil)) ?? []
        for file in files { try? FileManager.default.removeItem(at: file) }
        ImageCache.shared.removeAll()
    }
}

enum PhotoStorageError: LocalizedError {
    case encodingFailed

    var errorDescription: String? {
        switch self {
        case .encodingFailed: return "The photo couldn't be saved. Try taking it again."
        }
    }
}

extension UIImage {
    /// Returns an upright copy no larger than `maxPixelSize` on its long edge. Rendering also
    /// bakes in the orientation (including the front camera's mirroring), so the saved JPEG
    /// looks the same in every viewer.
    func downscaled(maxPixelSize: CGFloat) -> UIImage {
        let pixelW = size.width * scale
        let pixelH = size.height * scale
        let longest = max(pixelW, pixelH)
        let factor = longest > maxPixelSize ? maxPixelSize / longest : 1
        let target = CGSize(width: (pixelW * factor).rounded(), height: (pixelH * factor).rounded())

        let format = UIGraphicsImageRendererFormat.default()
        format.scale = 1
        format.opaque = true
        return UIGraphicsImageRenderer(size: target, format: format).image { _ in
            draw(in: CGRect(origin: .zero, size: target))
        }
    }
}
